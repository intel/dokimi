"""
Writes the locked conda environments Intel CI tests the conda package in.

For each Python version the recipe declares, ci/conda-lock/linux-64-py<version>.txt
lists, in the explicit format `conda create --file` reads, the conda-forge
builds that the recipe's run and test requirements and ci/config.yml's test
list resolve to. ci/hooks.py installs a pull request's or a main push's test
environment from it, so a new conda-forge build cannot fail them; a tag and
the weekly schedule resolve the latest builds instead. Only builds at least
--min-age-days old are taken, as the uv locks' --exclude-newer=P7D does.

It solves with py-rattler, which conda's solver cannot do: conda has no option
that leaves out the builds newer than a date. Usage, from a Python with
py-rattler and PyYAML (the version .github/workflows/conda-lock.yml installs):
  python ci/lock.py [--python 3.14 ...] [--min-age-days 7]
"""

import argparse
import asyncio
import datetime
import json
import sys
from pathlib import Path

import hooks
import matrix

CHANNEL = "conda-forge"
SPECS_PREFIX = "# specs: "
# The runner the locks are for; fixed, so they do not follow the machine that writes them.
PLATFORM = "linux-64"
VIRTUAL_PACKAGES = (("__unix", "0", "0"), ("__linux", "5.15", "0"),
                    ("__glibc", "2.28", "0"), ("__archspec", "1", "x86_64"))


class LockError(Exception):
    """Raised when the recipe cannot be read or py-rattler is missing."""


def recipe() -> Path:
    """The conda-build recipe, the only conda build system the locks support."""
    system, selector = matrix.detect(hooks.ROOT, "")
    if system != "conda-build":
        raise LockError(f"locks need a conda-build recipe, found {system}")
    return selector


def specs(version: str) -> list[str]:
    """What the test environment of one Python version resolves, but the package itself."""
    meta = hooks.read_yaml(recipe()) or {}
    run = (meta.get("requirements") or {}).get("run") or []
    test = (meta.get("test") or {}).get("requires") or []
    requires, _, _ = hooks.test_requirements()
    return [f"python {hooks.test_python(version)}", *run, *test, *requires]


def locked_specs(path: Path) -> list[str] | None:
    """The specs a lock file was solved from, None for a file without them."""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(SPECS_PREFIX):
            return json.loads(line.removeprefix(SPECS_PREFIX))
    return None


def solve(wanted: list[str], min_age_days: int) -> list:
    """The records the specs resolve to, from builds at least min_age_days old, sorted by name."""
    try:
        import rattler
        from rattler.package.build_string import BuildString
    except ModuleNotFoundError as error:
        raise LockError("ci/lock.py needs py-rattler: pip install py-rattler") from error
    virtual = [
        rattler.GenericVirtualPackage(rattler.PackageName(name), rattler.Version(version), BuildString(build))
        for name, version, build in VIRTUAL_PACKAGES
    ]
    try:
        records = asyncio.run(rattler.solve(
            [CHANNEL],
            wanted,
            platforms=[PLATFORM, "noarch"],
            virtual_packages=virtual,
            exclude_newer=datetime.timedelta(days=min_age_days),
            # conda-forge has timestamped every build for years; one without is old
            timestamp_policy="allow-missing",
        ))
    except Exception as error:
        raise LockError(f"the solve of {wanted} failed: {error}") from error
    if not records:
        raise LockError(f"the solve of {wanted} returned no packages")
    return sorted(records, key=lambda record: record.name.normalized)


def render(wanted: list[str], records: list, min_age_days: int) -> str:
    """The lock file: a header naming its specs, then one URL#sha256 per record, sorted by package name."""
    lines = [
        "# Copyright (C) 2026 Intel Corporation",
        "# SPDX-License-Identifier: Apache-2.0",
        "",
        "# Generated by ci/lock.py; regenerate with: python ci/lock.py",
        SPECS_PREFIX + json.dumps(wanted),
        f"# min-age-days: {min_age_days}",
        f"# platform: {PLATFORM}",
        "@EXPLICIT",
    ]
    for record in records:
        digest = record.sha256.hex() if isinstance(record.sha256, bytes) else record.sha256
        if not digest:
            raise LockError(f"{record.url} has no sha256 in the repodata")
        lines.append(f"{record.url}#{digest}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Solves and writes the lock of each requested Python version."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--python", action="append", help="a declared version; default all")
    parser.add_argument("--min-age-days", type=int, default=7)
    args = parser.parse_args(argv)
    declared = [p.version for p in matrix.declared("conda-build", recipe())]
    unknown = sorted(set(args.python or []) - set(declared))
    if unknown:
        raise LockError(f"not declared: {', '.join(unknown)}; declared: {', '.join(declared)}")
    written = set()
    for version in args.python or declared:
        wanted = specs(version)
        path = hooks.lock_path(version, PLATFORM)
        path.parent.mkdir(parents=True, exist_ok=True)
        text = render(wanted, solve(wanted, args.min_age_days), args.min_age_days)
        path.write_text(text, encoding="utf-8", newline="\n")  # LF on a Windows host too: the runners read it
        written.add(path)
        print(f"lock: wrote {path.relative_to(hooks.ROOT)}", flush=True)
    if not args.python:
        # A full run owns the directory: the lock of a version the recipe no longer declares goes
        for path in sorted(hooks.CONDA_LOCKS.glob(f"{PLATFORM}-py*.txt")):
            if path not in written:
                path.unlink()
                print(f"lock: removed {path.relative_to(hooks.ROOT)}", flush=True)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (LockError, hooks.HookError, matrix.DeclarationError, OSError) as error:
        print(f"lock: {error}", file=sys.stderr)
        sys.exit(1)
