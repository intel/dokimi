"""Probes for eval definitions that are config or code: promptfoo, OpenAI evals
registry specs, Inspect AI tasks.

An Inspect ``@task`` file is Python: it is scanned as text with regular
expressions and never imported or run.

A config that names its dataset files (promptfoo ``tests: file://tests.csv``, an
OpenAI evals ``samples_jsonl``, an Inspect ``json_dataset("data.jsonl",
FieldSpec(...))``) lists them in ``details["references"]``; the tree scan
(:mod:`dokimi.task_formats.links`) uses that to read those files as the format
the config says they are.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path
from typing import Any

from dokimi.task_formats.model import KIND_ANSWER_ONLY, KIND_EXECUTABLE, Fingerprint, Report
from dokimi.task_formats.source import FileSource, first_rows, key_share


def reference(path: Path, fmt: str, **hint: Any) -> dict[str, Any]:
    """One ``details["references"]`` entry: *path* is read as *fmt*, with *hint*."""
    return {"path": str(path), "format": fmt, **hint}


def _local(base: Path, value: str) -> Path | None:
    """*value* as a local path relative to *base*, or ``None`` for a URL or a glob."""
    value = value.removeprefix("file://")
    if "://" in value or any(c in value for c in "*?[{"):
        return None
    return (base / value) if not Path(value).is_absolute() else Path(value)


# --- promptfoo (promptfoo.dev/docs/configuration/reference) -------------------

_PROMPTFOO_SCHEMA = "promptfoo.dev/config-schema.json"
_PROMPTFOO_KEYS = ("prompts", "providers", "targets", "tests", "scenarios", "redteam")
FORMAT_PROMPTFOO_TESTS = "promptfoo-tests"


def _promptfoo_named(source: FileSource) -> bool:
    """promptfooconfig.yaml, and the variants the examples use (promptfooconfig.redteam.yaml)."""
    return source.path.name.startswith("promptfooconfig") and source.suffix in (".yaml", ".yml", ".json")


class PromptfooProbe:
    name = "promptfoo"
    target = "file"

    def fingerprint(self, source: FileSource) -> Fingerprint | None:
        if source.suffix not in (".yaml", ".yml", ".json"):
            return None
        named = _promptfoo_named(source)
        schema = _PROMPTFOO_SCHEMA in (source.text or "")[:2000]
        data = source.data
        signals = (("file name",) if named else ()) + (("config $schema",) if schema else ())
        if not isinstance(data, dict):
            return Fingerprint(0.6, signals) if signals else None
        keys = tuple(k for k in _PROMPTFOO_KEYS if k in data)
        has_target = "providers" in data or "targets" in data
        shaped = "prompts" in data and has_target and any(k in data for k in ("tests", "scenarios", "redteam"))
        if not signals and not shaped:
            return None
        return Fingerprint(min(1.0, 0.5 + 0.1 * len(signals) + 0.1 * len(keys)), signals + keys)

    def describe(self, source: FileSource) -> Report:
        data: dict[str, Any] = source.data if isinstance(source.data, dict) else {}
        tests = data.get("tests")
        report = Report(source.path, self.name, KIND_ANSWER_ONLY,
                        items=len(tests) if isinstance(tests, list) else None)
        report.problems.extend(source.problems)
        if source.data is not None and not data:
            report.problems.append("not a mapping")
        asserts = isinstance(data.get("defaultTest"), dict) and "assert" in data["defaultTest"]
        asserts = asserts or any(isinstance(t, dict) and t.get("assert")
                                 for t in (tests if isinstance(tests, list) else []))
        report.set_parts({
            "instruction": bool(data.get("prompts")),
            "environment": bool(data.get("providers") or data.get("targets")),
            "verifier": asserts or "redteam" in data,
            "metadata": bool(data.get("description")),
        })
        if "redteam" in data:
            report.details["redteam"] = True  # the tests are generated by `promptfoo redteam`
        if isinstance(tests, str):
            report.details["tests_from"] = tests
            local = _local(source.path.parent, tests)
            if local is not None:
                report.details["references"] = [reference(local, FORMAT_PROMPTFOO_TESTS)]
        elif data and tests is None and not any(k in data for k in ("scenarios", "redteam")):
            report.problems.append("no tests")
        if data and not data.get("prompts") and "redteam" not in data:
            report.problems.append("no prompts")
        return report


class PromptfooTestsProbe:
    """A promptfoo test-case file: CSV with ``__expected`` columns, or a list of ``{vars, assert}``."""

    name = FORMAT_PROMPTFOO_TESTS
    target = "file"

    def fingerprint(self, source: FileSource) -> Fingerprint | None:
        if source.suffix not in (".csv", ".yaml", ".yml", ".json", ".jsonl"):
            return None
        rows = first_rows(source.rows)
        if not rows:
            return None
        if source.suffix == ".csv":
            expected = any(k.startswith("__expected") for k in rows[0])
            return Fingerprint(0.8, ("__expected column",)) if expected else None
        share = key_share(rows, "vars")
        if share < 0.8 or not any("assert" in r for r in rows):
            return None
        return Fingerprint(0.75 * share, ("vars", "assert"))

    def describe(self, source: FileSource) -> Report:
        rows = source.rows or []
        report = Report(source.path, self.name, KIND_ANSWER_ONLY, items=len(rows))
        report.problems.extend(source.problems)
        expected = any(k.startswith("__expected") for r in rows[:1] for k in r)
        report.set_parts({
            "instruction": bool(rows),
            "verifier": expected or any(r.get("assert") for r in rows),
        })
        if source.hint.get("referenced_by"):
            report.details["config"] = source.hint["referenced_by"]
        return report


# --- OpenAI evals registry (evals/registry/evals/*.yaml) -----------------------

FORMAT_OPENAI_EVALS = "openai-evals"


def _openai_specs(data: Any) -> dict[str, dict[str, Any]]:
    """The run specs of a registry file: entries whose ``class`` is an eval (``evals.elsuite.*``).

    ``registry/completion_fns`` and ``registry/solvers`` use the same layout for
    ``evals.completion_fns.*`` and ``evals.solvers.*`` classes: those are not evals.
    """
    if not isinstance(data, dict):
        return {}
    return {str(k): v for k, v in data.items() if isinstance(v, dict)
            and str(v.get("class", "")).startswith("evals.elsuite.") and ":" in str(v.get("class", ""))}


def _samples_files(spec: dict[str, Any]) -> list[str]:
    args = spec.get("args")
    value = args.get("samples_jsonl") if isinstance(args, dict) else None
    values = value if isinstance(value, list) else [value]
    return [v for v in values if isinstance(v, str)]


class OpenAIEvalsSpecProbe:
    """A registry YAML: ``<name>: {id, metrics}`` plus ``<name>.dev.v0: {class, args}``."""

    name = "openai-evals-spec"
    target = "file"

    def fingerprint(self, source: FileSource) -> Fingerprint | None:
        if source.suffix not in (".yaml", ".yml") or not _openai_specs(source.data):
            return None
        return Fingerprint(0.9, ("class: evals.elsuite.*",))

    def describe(self, source: FileSource) -> Report:
        specs = _openai_specs(source.data)
        report = Report(source.path, self.name, KIND_ANSWER_ONLY, items=len(specs))
        report.problems.extend(source.problems)
        data = source.data if isinstance(source.data, dict) else {}
        # registry/evals/<file>.yaml names its samples relative to registry/data/.
        data_root = source.path.parent.parent / "data" if source.path.parent.name == "evals" else None
        refs = []
        for spec in specs.values():
            graded = "modelgraded" in str(spec["class"])
            for rel in _samples_files(spec):
                if data_root is not None:
                    refs.append(reference(data_root / rel, FORMAT_OPENAI_EVALS, model_graded=graded))
        missing = sorted({r["path"] for r in refs if not Path(r["path"]).is_file()})
        if missing:
            report.problems.append(f"{len(missing)} samples files not found: "
                                   + ", ".join(Path(m).name for m in missing[:3]))
        report.set_parts({
            "instruction": bool(refs) or any(_samples_files(s) for s in specs.values()),
            "verifier": True,  # the eval class is the grader
            "metadata": any(isinstance(v, dict) and v.get("description") for v in data.values()),
        })
        report.details["classes"] = dict(Counter(str(s["class"]).split(":")[-1] for s in specs.values()))
        report.details["model_graded"] = sum("modelgraded" in str(s["class"]) for s in specs.values())
        if refs:
            report.details["references"] = refs
        return report


# --- Inspect AI @task files ----------------------------------------------------

_INSPECT_IMPORT = re.compile(r"^\s*(?:from\s+inspect_ai(?:\.\w+)*\s+import|import\s+inspect_ai)\b", re.M)
_TASK_DECORATOR = re.compile(r"^\s*@(?:inspect_ai\.)?task\b", re.M)
_SANDBOX = re.compile(r"\bsandbox\s*=")
_SCORER = re.compile(r"\bscorer\s*=")
_DATASET = re.compile(r"\bdataset\s*=|\bSample\s*\(|\b\w+_dataset\s*\(")
_SOLVER = re.compile(r"\b(?:solver|plan)\s*=")
# json_dataset("x.jsonl", ...), csv_dataset(csv_file="x.csv"), example_dataset(name="x"), hf_dataset(path="x")
_DATASET_CALL = re.compile(
    r"\b(?P<loader>json_dataset|csv_dataset|file_dataset|example_dataset|hf_dataset)\(\s*"
    r"(?:(?:name|json_file|csv_file|path)\s*=\s*)?[rbuf]?[\"'](?P<arg>[^\"']+)[\"']")
# Bounded, and an unclosed FieldSpec( stops at the next one: a flood of them costs linear time.
_FIELD_SPEC = re.compile(r"\bFieldSpec\((?P<args>(?:(?!FieldSpec\()[^)]){0,1000})\)")
_FIELD_ARG = re.compile(r"\b(input|target|id|choices)\s*=\s*[\"']([^\"']+)[\"']")
_RECORD_TO_SAMPLE = re.compile(r"\bsample_fields\s*=\s*(?!FieldSpec\b)[A-Za-z_]\w*")


def _inspect_datasets(text: str) -> list[dict[str, Any]]:
    """Each dataset call with its FieldSpec, the one between it and the next call."""
    calls = list(_DATASET_CALL.finditer(text))
    found = []
    for i, call in enumerate(calls):
        end = calls[i + 1].start() if i + 1 < len(calls) else len(text)
        spec = _FIELD_SPEC.search(text, call.end(), end)
        fields = dict(_FIELD_ARG.findall(spec["args"])) if spec else {}
        found.append({"loader": call["loader"], "source": call["arg"], "fields": fields})
    return found


def _inspect_reference(base: Path, dataset: dict[str, Any]) -> dict[str, Any] | None:
    hint = {"fields": dataset["fields"]} if dataset["fields"] else {}
    if dataset["loader"] == "example_dataset":
        # Inspect's bundled examples: matched by file name wherever the scan finds it.
        return reference(base / f"{dataset['source']}.jsonl", "inspect-samples", match="name", **hint)
    if dataset["loader"] == "hf_dataset":
        return None
    local = _local(base, dataset["source"])
    return reference(local, "inspect-samples", **hint) if local is not None else None


class InspectTaskProbe:
    name = "inspect-task"
    target = "file"

    def fingerprint(self, source: FileSource) -> Fingerprint | None:
        if source.suffix != ".py" or not source.text:
            return None
        if not _INSPECT_IMPORT.search(source.text) or not _TASK_DECORATOR.search(source.text):
            return None
        return Fingerprint(0.9, ("imports inspect_ai", "@task"))

    def describe(self, source: FileSource) -> Report:
        text = source.text or ""
        sandboxed = bool(_SANDBOX.search(text))
        report = Report(source.path, self.name, KIND_EXECUTABLE if sandboxed else KIND_ANSWER_ONLY,
                        items=len(_TASK_DECORATOR.findall(text)))
        report.problems.extend(source.problems)
        report.set_parts({
            "instruction": bool(_DATASET.search(text)),
            "environment": sandboxed,
            "verifier": bool(_SCORER.search(text)),
            "metadata": False,
        })
        report.details["solver"] = bool(_SOLVER.search(text))
        report.details["scan"] = "static text scan; the file was not imported"
        datasets = _inspect_datasets(text)
        if datasets:
            report.details["datasets"] = datasets
        if _RECORD_TO_SAMPLE.search(text):
            # A record_to_sample function maps fields in code: the scan cannot follow it.
            report.details["record_to_sample"] = True
        refs = [r for r in (_inspect_reference(source.path.parent, d) for d in datasets) if r]
        if refs:
            report.details["references"] = refs
        return report
