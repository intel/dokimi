def test_tools_lock_has_every_requested_pin() -> None:
    """An exact pin in requirements-ci.txt (ruff, zizmor, ...) must be the version the tools lock resolves."""
    locked = pins("requirements-ci.lock.txt")
    for line in (ROOT / "requirements-ci.txt").read_text(encoding="utf-8").splitlines():
        stripped = line.split("#", 1)[0].strip()
        if stripped and not PIN.match(stripped):
            # Only a bare name or an exact pin can be checked against the lock.
            assert BARE_NAME.match(stripped), f"requirements-ci.txt line not checked: {line!r}"
            assert canonical(stripped) in locked, (
                f"requirements-ci.txt lists {stripped} but requirements-ci.lock.txt has no pin for it"
            )
        if m := PIN.match(line):
            assert m[2] in locked.get(canonical(m[1]), set()), (
                f"requirements-ci.txt pins {m[1]}=={m[2]} but requirements-ci.lock.txt has "
                f"{sorted(locked.get(canonical(m[1]), set()))}"
            )


@pytest.mark.parametrize(("base", "name"), STACKED_LOCKS)
def test_stacked_lock_pins_agree(base: str, name: str) -> None:
    """A refresh of one lock alone makes `pip install -r <base> -r <name>` unresolvable."""
    assert pins(base) and pins(name), (base, name)
    for env in ENVIRONMENTS:
        held = installed_pins(base, env)
        stacked = installed_pins(name, env)
        drift = {p: (v, held[p]) for p, v in stacked.items() if p in held and v != held[p]}
        where = f"{env['sys_platform']}, Python {env['python_version']}"
        assert not drift, (
            f"regenerate {name} after {base} with its header command ({where}): {drift}"
        )


