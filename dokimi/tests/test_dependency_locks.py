"""The uv locks stay readable by Renovate and installable together."""

from __future__ import annotations

import re
import shlex
from pathlib import Path

import pytest
from packaging.markers import Marker

ROOT = Path(__file__).resolve().parents[1]
# The locks .github/renovate.json5 hands to the pip-compile manager.
RENOVATE_LOCKS = ("requirements.lock.txt", "requirements-ci.lock.txt", "requirements-mutation.lock.txt")
# Installed together with --require-hashes (ci.yml, docs.yml, .agent-eval/Dockerfile,
# make dev), so a pin both carry has to be the same version.
STACKED_LOCKS = (
    ("requirements.lock.txt", "requirements-ci.lock.txt"),
    ("requirements.lock.txt", "requirements-docs.lock.txt"),
    ("requirements.lock.txt", "requirements-mutation.lock.txt"),
    ("requirements-ci.lock.txt", "requirements-docs.lock.txt"),
)
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)")
HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}(?!\w)")
BARE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
HASHED_LOCKS = (
    "requirements.lock.txt",
    "requirements-ci.lock.txt",
    "requirements-docs.lock.txt",
    "requirements-mutation.lock.txt",
)
# Where the stacked locks are installed: CI's Pythons, and make dev on any OS.
ENVIRONMENTS = [
    {
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
        "python_version": f"3.{minor}",
        "python_full_version": f"3.{minor}.0",
        "sys_platform": sys_platform,
        "platform_system": system,
        "os_name": os_name,
        "platform_machine": machine,
    }
    for minor in (11, 12, 13, 14)
    for sys_platform, system, os_name, machine in (
        ("linux", "Linux", "posix", "x86_64"),
        ("darwin", "Darwin", "posix", "arm64"),
        ("win32", "Windows", "nt", "AMD64"),
    )
]


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def header_command(name: str) -> list[str]:
    lines = (ROOT / name).read_text(encoding="utf-8").splitlines()
    assert lines[0] == "# This file was autogenerated by uv via the following command:", name
    return shlex.split(lines[1].lstrip("# "))


def compile_command(name: str) -> str:
    """The uv command in the file's header comment, continuation lines joined. Comments elsewhere in the header do not count."""
    parts: list[str] = []
    collecting = False
    for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        body = line[1:].strip()
        if not collecting:
            if "uv pip compile" not in body:
                continue
            collecting = True
        parts.append(body)
        if not body.endswith("\\"):
            break
    return " ".join(parts).replace("\\", " ")


def pins(name: str) -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
        if m := PIN.match(line):
            found.setdefault(canonical(m[1]), set()).add(m[2])
    return found


def installed_pins(name: str, env: dict[str, str]) -> dict[str, set[str]]:
    """The pins pip takes from the lock on `env` (over the running interpreter's values)."""
    found: dict[str, set[str]] = {}
    for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
        if m := PIN.match(line):
            marker = line.partition(";")[2].rstrip().removesuffix("\\").strip()
            if not marker or Marker(marker).evaluate(env):
                found.setdefault(canonical(m[1]), set()).add(m[2])
    return found


@pytest.mark.parametrize("name", RENOVATE_LOCKS)
def test_lock_header_options_are_long_with_equals(name: str) -> None:
    """Renovate's pip-compile manager rejects `-c x` and `--constraint x` and skips the file."""
    cmd = header_command(name)
    assert cmd[:3] == ["uv", "pip", "compile"], cmd
    for arg in cmd[3:]:
        if arg.startswith("-"):
            assert arg.startswith("--"), f"{name}: short option {arg} (write its --long=value form)"
        else:
            # Renovate takes every positional as a source file; a value after a
            # space-separated option would be read as one.
            assert (ROOT / arg).is_file(), f"{name}: {arg} is not a file"
            assert not arg.endswith(".lock.txt"), f"{name}: write {arg} as --opt={arg}"


@pytest.mark.parametrize("name", HASHED_LOCKS)
def test_lock_is_compiled_with_hashes(name: str) -> None:
    """Every install is `--require-hashes`, so each lock must have been compiled with hashes."""
    assert "--generate-hashes" in compile_command(name).split(), name


def test_tools_lock_is_constrained_to_main_lock() -> None:
    """The tools lock is compiled against the main lock, so shared pins cannot drift."""
    assert "--constraint=requirements.lock.txt" in header_command("requirements-ci.lock.txt")


@pytest.mark.parametrize("name", HASHED_LOCKS)
def test_every_pin_has_hashes(name: str) -> None:
    lines = (ROOT / name).read_text(encoding="utf-8").splitlines()
    unhashed = []
    for i, line in enumerate(lines):
        if not PIN.match(line):
            continue
        # A pin and its hashes: each line ends with a backslash but the last.
        block = [line]
        while block[-1].rstrip().endswith("\\") and i + len(block) < len(lines):
            block.append(lines[i + len(block)])
        hashes = [b for b in block if "--hash=" in b]
        if not hashes or not all(HASH.search(h) for h in hashes):
            unhashed.append(line)
    assert not unhashed, f"{name}: pins without a valid --hash=sha256 line: {unhashed}"


@pytest.mark.parametrize("name", ("requirements-ci.lock.txt", "requirements-mutation.lock.txt"))
def test_tools_locks_are_constrained_to_main_lock_by_header(name: str) -> None:
    assert "--constraint=requirements.lock.txt" in header_command(name)


def test_mutation_tool_stays_out_of_the_shared_tools_lock() -> None:
    """CI, the release job, pip-audit's tools step and the eval image install the tools lock;
    only mutation.yml installs mutmut, from its own lock."""
    assert "mutmut" not in pins("requirements-ci.lock.txt")
    assert pins("requirements-mutation.lock.txt")["mutmut"] == {"3.8.0"}
    requested = (ROOT / "requirements-mutation.txt").read_text(encoding="utf-8")
    assert "mutmut==3.8.0" in requested


def test_tools_lock_has_every_requested_pin() -> None:
    """An exact pin in requirements-ci.txt (ruff, zizmor, ...) must be the version the tools lock resolves."""
    locked = pins("requirements-ci.lock.txt")
    for line in (ROOT / "requirements-ci.txt").read_text(encoding="utf-8").splitlines():
        stripped = line.split("#", 1)[0].strip()
        if stripped and not PIN.match(stripped):
            # Only a bare name or an exact pin can be checked against the lock.
            assert BARE_NAME.match(stripped), f"requirements-ci.txt line not checked: {line!r}"
            assert canonical(stripped) in locked, (
                f"requirements-ci.txt lists {stripped} but requirements-ci.lock.txt has no pin for it"
            )
        if m := PIN.match(line):
            assert m[2] in locked.get(canonical(m[1]), set()), (
                f"requirements-ci.txt pins {m[1]}=={m[2]} but requirements-ci.lock.txt has "
                f"{sorted(locked.get(canonical(m[1]), set()))}"
            )


@pytest.mark.parametrize(("base", "name"), STACKED_LOCKS)
def test_stacked_lock_pins_agree(base: str, name: str) -> None:
    """A refresh of one lock alone makes `pip install -r <base> -r <name>` unresolvable."""
    assert pins(base) and pins(name), (base, name)
    for env in ENVIRONMENTS:
        held = installed_pins(base, env)
        stacked = installed_pins(name, env)
        drift = {p: (v, held[p]) for p, v in stacked.items() if p in held and v != held[p]}
        where = f"{env['sys_platform']}, Python {env['python_version']}"
        assert not drift, (
            f"regenerate {name} after {base} with its header command ({where}): {drift}"
        )


@pytest.mark.parametrize("name", RENOVATE_LOCKS)
def test_lock_refresh_keeps_the_seven_day_cooldown(name: str) -> None:
    """A refresh (`--upgrade`) must not take a release younger than a week."""
    assert "--exclude-newer=P7D" in header_command(name), name


def test_tools_lock_exempts_only_pins_younger_than_the_cooldown() -> None:
    """certifi comes from the main lock (a security bump), uv is an exact pin in requirements-ci.txt,
    and virtualenv is a security bump (CVE-2026-113722)."""
    cmd = header_command("requirements-ci.lock.txt")
    exempt = {a.split("=", 1)[1] for a in cmd if a.startswith("--exclude-newer-package=")}
    assert exempt == {"certifi=false", "uv=false", "virtualenv=false"}, exempt
