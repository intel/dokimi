@pytest.mark.parametrize("name", HASHED_LOCKS)
def test_every_pin_has_hashes(name: str) -> None:
    lines = (ROOT / name).read_text(encoding="utf-8").splitlines()
    unhashed = []
    for i, line in enumerate(lines):
        if not PIN.match(line):
            continue
        # A pin and its hashes: each line ends with a backslash but the last.
        block = [line]
        while block[-1].rstrip().endswith("\\") and i + len(block) < len(lines):
            block.append(lines[i + len(block)])
        hashes = [b for b in block if "--hash=" in b]
        if not hashes or not all(HASH.search(h) for h in hashes):
            unhashed.append(line)
    assert not unhashed, f"{name}: pins without a valid --hash=sha256 line: {unhashed}"


